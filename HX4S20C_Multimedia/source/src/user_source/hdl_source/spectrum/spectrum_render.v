//=============================================================================
//  spectrum_render.v : 把 32 段柱高画成 RGB 像素，叠加在视频的最后一级
//
//  位置：放在 param_osd 之后、rgb_to_axis 之前，也就是整条像素通路的最后一级。
//        这样它压在底带、字幕、参数行之上（那些都在 420 行以下或 30 行以上），
//        而柱状图占的是 y = 304 ~ 419 这块纯图像区，跟已有的任何叠加都不重叠：
//          · 标题带      y = 2 ~ 30
//          · 滚动字幕    y = 424 ~ 439
//          · 信息行/参数行 y = 452 ~ 467
//
//  版式：32 段，每段 20 像素一格（柱宽 16、间隔 4），32×20 = 640 正好满宽；
//        柱底固定在第 419 行（底带上沿的上一行），最高 116 像素到第 304 行。
//        x -> 段号用 x*205>>12 近似 x/20，只有加法器和一个 10x8 乘法，不用除法器。
//
//  观感：柱区底色先压暗到 62.5%，柱体再以 75% 不透明度盖上去，照片还看得见
//        但柱子很跳；柱顶 2 行画一条亮色峰值帽，每帧 -1 像素慢慢落下来。
//
//  时序：输入先打一拍（d1），再算混合，输出再打一拍，整条支路 2 拍延迟，
//        de/hs/vs 与像素始终同步。为什么要多这一拍：param_osd 的显示运算本身
//        就有十几级逻辑，如果直接在本级组合混合后再寄存，最差路径会变成
//        "param_ctrl -> rgb_adjust 乘法 -> param_osd 加法 -> 本模块 mux"，
//        32 级逻辑、38.7 ns，只剩 0.94 ns 余量。切成两拍之后这条路径被拆开，
//        最终布线 video_clk 余量回到 +8.5 ns（详见 doc/验收报告.md）。
//=============================================================================

module spectrum_render (
    input  wire        I_clk,
    input  wire        I_rst,        // 高有效

    input  wire        I_de,
    input  wire        I_hs,
    input  wire        I_vs,
    input  wire [23:0] I_rgb,

    input  wire [255:0] I_cur,       // 32 段柱高
    input  wire [255:0] I_peak,      // 32 段峰值帽高度
    input  wire         I_en,        // 频谱数据有效（首帧之前不画，避免上电乱柱）

    output reg         O_de,
    output reg         O_hs,
    output reg         O_vs,
    output reg  [23:0] O_rgb
);

//-----------------------------------------------------------------------------
//  版式常量
//-----------------------------------------------------------------------------
localparam [9:0] Y_BASE = 10'd419;   // 柱底所在行
localparam [9:0] Y_TOP  = 10'd304;   // 柱最高能到的行（419-115）

// 渲染级自检：置 1 时柱高不再来自频谱数据，而是固定的阶梯（第 n 段 3n+12 像素）。
// 排查"屏幕上看不到柱子"时，把它改成 1 重新综合一版：
//   能看到阶梯 → 渲染级、叠加位置、时序都对，问题在音频/FFT 那边；
//   看不到     → 问题在像素通路或 bit 没下进去。默认 0，不占逻辑（综合会剪掉）。
localparam integer SELFTEST = 0;

//-----------------------------------------------------------------------------
//  第一拍：输入寄存（把上游 param_osd 的长组合路径切在这里）
//-----------------------------------------------------------------------------
reg        d1_de, d1_hs, d1_vs;
reg [23:0] d1_rgb;

always @(posedge I_clk or posedge I_rst) begin
    if (I_rst) begin
        d1_de  <= 1'b0;
        d1_hs  <= 1'b0;
        d1_vs  <= 1'b0;
        d1_rgb <= 24'd0;
    end else begin
        d1_de  <= I_de;
        d1_hs  <= I_hs;
        d1_vs  <= I_vs;
        d1_rgb <= I_rgb;
    end
end

//-----------------------------------------------------------------------------
//  行/列计数（跟着已经打过一拍的像素走，只数有效像素）
//-----------------------------------------------------------------------------
reg [9:0] x_cnt;
reg [9:0] y_cnt;
reg vs_d;
always @(posedge I_clk or posedge I_rst) begin
    if (I_rst) vs_d <= 0;
    else vs_d <= d1_vs;
end

always @(posedge I_clk or posedge I_rst) begin
    if (I_rst) begin
        x_cnt <= 10'd0;
        y_cnt <= 10'd0;
    end else if (d1_vs != vs_d) begin
        x_cnt <= 10'd0;
        y_cnt <= 10'd0;
    end else if (d1_de) begin
        if (x_cnt == 10'd639) begin
            x_cnt <= 10'd0;
            y_cnt <= y_cnt + 10'd1;
        end else begin
            x_cnt <= x_cnt + 10'd1;
        end
    end
end

//-----------------------------------------------------------------------------
//  列 -> 段号：bidx = x*205 >> 12 ≈ x/20
//-----------------------------------------------------------------------------
wire [17:0] xm   = {8'd0, x_cnt} * 18'd205;
wire [4:0]  bidx = xm[16:12];
wire [9:0]  b20  = {1'b0, bidx, 4'b0000} + {3'd0, bidx, 2'b00};   // bidx*20
wire [9:0]  bx   = x_cnt - b20;

//-----------------------------------------------------------------------------
//  行 -> 柱内高度
//-----------------------------------------------------------------------------
wire [9:0]  yf   = Y_BASE - y_cnt;                    // 0 ~ 116
wire        in_y = (y_cnt >= Y_TOP) && (y_cnt <= Y_BASE);
wire        in_x = (bx < 10'd16);

wire [7:0]  st_hgt = {2'd0, bidx} + {1'b0, bidx, 1'b0} + 8'd12;   // 3*bidx+12

wire [7:0]  hgt  = SELFTEST ? st_hgt : I_cur [bidx*8 +: 8];
wire [7:0]  pk   = SELFTEST ? 8'd0   : I_peak[bidx*8 +: 8];
wire        ena  = SELFTEST ? 1'b1   : I_en;

wire        lit  = (yf < {2'd0, hgt});
wire        cap  = (pk != 8'd0) &&
                   ((yf == {2'd0, pk}) || ((yf + 10'd1) == {2'd0, pk}));

//-----------------------------------------------------------------------------
//  配色：4 个色区轮流，低频红 -> 橙 -> 绿 -> 高频蓝
//-----------------------------------------------------------------------------
reg [7:0] bar_r, bar_g, bar_b;

always @(*) begin
    case (bidx[4:3])
        2'd0:    begin bar_r = 8'd255; bar_g = 8'd64;  bar_b = 8'd64;  end
        2'd1:    begin bar_r = 8'd255; bar_g = 8'd176; bar_b = 8'd48;  end
        2'd2:    begin bar_r = 8'd64;  bar_g = 8'd224; bar_b = 8'd96;  end
        default: begin bar_r = 8'd64;  bar_g = 8'd160; bar_b = 8'd255; end
    endcase
end

//-----------------------------------------------------------------------------
//  混合：先把柱区底色压暗到 62.5%，再让柱体盖上去 75% 不透明度
//    bk  = in/2 + in/8              （0.625 * in）
//    out = bk/4 + c/2 + c/4         （0.25 * bk + 0.75 * c）
//  只用移位和加法，没有乘法器。
//-----------------------------------------------------------------------------
function [7:0] dim25;          // 0.625 * a
    input [7:0] a;
    begin
        dim25 = (a >> 1) + (a >> 3);
    end
endfunction

function [7:0] mix75;          // 0.25*a + 0.75*b
    input [7:0] a;
    input [7:0] b;
    begin
        mix75 = (a >> 2) + (b >> 1) + (b >> 2);
    end
endfunction

//-----------------------------------------------------------------------------
//  像素合成
//-----------------------------------------------------------------------------
reg [7:0] r_o, g_o, b_o;

always @(*) begin
    r_o = d1_rgb[23:16];
    g_o = d1_rgb[15:8];
    b_o = d1_rgb[7:0];

    if (d1_de && in_y && ena) begin
        // 柱区整条压暗，形成一块"可视化面板"，照片仍隐约可见
        r_o = dim25(r_o);
        g_o = dim25(g_o);
        b_o = dim25(b_o);

        if (in_x) begin
            if (cap) begin
                // 峰值帽：不混合，亮白略偏青，任何底图上都看得见
                r_o = 8'd232;
                g_o = 8'd240;
                b_o = 8'd255;
            end else if (lit) begin
                r_o = mix75(r_o, bar_r);
                g_o = mix75(g_o, bar_g);
                b_o = mix75(b_o, bar_b);
            end
        end
    end
end

//-----------------------------------------------------------------------------
//  第二拍：输出寄存，de/hs/vs 与像素同步延迟
//-----------------------------------------------------------------------------
always @(posedge I_clk or posedge I_rst) begin
    if (I_rst) begin
        O_de  <= 1'b0;
        O_hs  <= 1'b0;
        O_vs  <= 1'b0;
        O_rgb <= 24'd0;
    end else begin
        O_rgb <= {r_o, g_o, b_o};
        O_de  <= d1_de;
        O_hs  <= d1_hs;
        O_vs  <= d1_vs;
    end
end

endmodule
