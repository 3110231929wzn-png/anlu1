wire rst_sd;
wire rst_mem;
wire rst_video;
reg [1:0] sys_lock_sync = 2'b00;
reg [1:0] video_lock_sync = 2'b00;

always @(posedge clk) begin
    if (!rst_n) begin
        sys_lock_sync <= 2'b00;
        video_lock_sync <= 2'b00;
    end else begin
        sys_lock_sync <= {sys_lock_sync[0], sys_pll_lock};
        video_lock_sync <= {video_lock_sync[0], video_pll_lock};
    end
end

reg [19:0] rst_cnt = 20'd0;
reg rst_all_reg = 1'b1;

always @(posedge clk) begin
    if (!rst_n) begin
        rst_cnt <= 20'd0;
        rst_all_reg <= 1'b1;
    end else if (!rst_all_reg) begin
        // 一旦复位释放，忽略后续微小的 PLL 抖动，防止系统在使用时随机复位
        rst_all_reg <= 1'b0;
    end else if (sys_lock_sync[1] && video_lock_sync[1]) begin
        // 等待 PLL 连续稳定 20ms @ 50MHz
        if (rst_cnt < 20'd1_000_000) begin
            rst_cnt <= rst_cnt + 1'b1;
            rst_all_reg <= 1'b1;
        end else begin
            rst_all_reg <= 1'b0;
        end
    end else begin
        rst_cnt <= 20'd0;
        rst_all_reg <= 1'b1;
    end
end

assign rst_all = rst_all_reg;
